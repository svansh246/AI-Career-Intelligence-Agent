from datetime import datetime


def generate_text_report(analysis):
    """
    Generate a text report from the current
    AI Career Assistant analysis structure.
    """

    profile = analysis.get(
        "profile",
        {}
    )

    if not isinstance(profile, dict):
        profile = {}

    skills = analysis.get(
        "skills",
        []
    )

    if not isinstance(skills, list):
        skills = [skills]

    strengths = profile.get(
        "strengths",
        []
    )

    weaknesses = profile.get(
        "weaknesses",
        []
    )

    recommendations = profile.get(
        "recommendations",
        []
    )

    report = []

    report.append("=" * 70)

    report.append(
        "AI CAREER ASSISTANT - RESUME ANALYSIS REPORT"
    )

    report.append("=" * 70)

    report.append("")

    report.append(
        f"Generated: "
        f"{datetime.now().strftime('%d-%m-%Y %H:%M:%S')}"
    )

    report.append("")

    # -----------------------------------------------------
    # BASIC INFORMATION
    # -----------------------------------------------------

    report.append(
        "1. BASIC INFORMATION"
    )

    report.append("-" * 70)

    report.append(
        f"Name: "
        f"{analysis.get('user_name', 'Not provided')}"
    )

    report.append(
        f"Resume: "
        f"{analysis.get('resume_name', 'Not provided')}"
    )

    report.append(
        f"Target Domain: "
        f"{analysis.get('target_domain', 'Not specified')}"
    )

    report.append("")

    # -----------------------------------------------------
    # READINESS
    # -----------------------------------------------------

    report.append(
        "2. CAREER READINESS"
    )

    report.append("-" * 70)

    report.append(
        f"Readiness Score: "
        f"{analysis.get('readiness_score', 0)}/100"
    )

    report.append("")

    # -----------------------------------------------------
    # SKILLS
    # -----------------------------------------------------

    report.append(
        "3. DETECTED SKILLS"
    )

    report.append("-" * 70)

    if skills:

        for skill in skills:

            report.append(
                f"- {skill}"
            )

    else:

        report.append(
            "No skills detected."
        )

    report.append("")

    # -----------------------------------------------------
    # PROFILE
    # -----------------------------------------------------

    report.append(
        "4. PROFILE ANALYSIS"
    )

    report.append("-" * 70)

    for key, value in profile.items():

        if key in [
            "strengths",
            "weaknesses",
            "recommendations",
            "resume_text_preview",
        ]:

            continue

        title = (
            str(key)
            .replace("_", " ")
            .title()
        )

        report.append(
            f"{title}: {value}"
        )

    report.append("")

    # -----------------------------------------------------
    # STRENGTHS
    # -----------------------------------------------------

    report.append(
        "5. STRENGTHS"
    )

    report.append("-" * 70)

    if strengths:

        for item in strengths:

            report.append(
                f"- {item}"
            )

    else:

        report.append(
            "No strengths recorded."
        )

    report.append("")

    # -----------------------------------------------------
    # WEAKNESSES
    # -----------------------------------------------------

    report.append(
        "6. AREAS FOR IMPROVEMENT"
    )

    report.append("-" * 70)

    if weaknesses:

        for item in weaknesses:

            report.append(
                f"- {item}"
            )

    else:

        report.append(
            "No weaknesses recorded."
        )

    report.append("")

    # -----------------------------------------------------
    # RECOMMENDATIONS
    # -----------------------------------------------------

    report.append(
        "7. CAREER RECOMMENDATIONS"
    )

    report.append("-" * 70)

    if recommendations:

        for item in recommendations:

            report.append(
                f"- {item}"
            )

    else:

        report.append(
            "No recommendations available."
        )

    report.append("")

    # -----------------------------------------------------
    # FOOTER
    # -----------------------------------------------------

    report.append("=" * 70)

    report.append(
        "Generated by AI Career Assistant"
    )

    report.append("=" * 70)

    return "\n".join(report)